// The only bridge between the window and the SSH connection.
const { contextBridge, ipcRenderer } = require('electron');

const invoke = channel => (...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('panel', {
  pinStatus: invoke('pin:status'),
  unlock: invoke('pin:unlock'),
  setPin: invoke('pin:set'),
  connect: invoke('connect'),
  serviceStatus: invoke('service:status'),
  serviceAction: invoke('service:action'),
  health: invoke('vds:health'),
  api: invoke('api'),
  startLogs: invoke('logs:start'),
  stopLogs: invoke('logs:stop'),
  pickRelease: invoke('update:pick'),
  pickAddon: invoke('addons:pick'),
  cancelAddon: invoke('addons:cancel'),
  installAddon: invoke('addons:install'),
  removeAddon: invoke('addons:remove'),
  runUpdate: invoke('update:run'),
  profiles: invoke('profiles:list'),
  saveProfile: invoke('profiles:save'),
  removeProfile: invoke('profiles:remove'),
  activateProfile: invoke('profiles:activate'),
  testProfile: invoke('profiles:test'),
  pickKeyFile: invoke('profiles:pickKey'),
  listBackups: invoke('backups:list'),
  backupNow: invoke('backups:now'),
  downloadBackup: invoke('backups:download'),
  restoreBackup: invoke('backups:restore'),
  exportCsv: invoke('export:csv'),
  history: invoke('history:list'),
  getAutostart: invoke('autostart:get'),
  setAutostart: invoke('autostart:set'),
  testView: invoke('testView'),
  startup: invoke('startup'),
  setupCheckToken: invoke('setup:checkToken'),
  setupInvite: invoke('setup:invite'),
  setupInstallServer: invoke('setup:installServer'),
  setupInstallHere: invoke('setup:installHere'),
  setupBundle: invoke('setup:bundle'),
  openPortal: invoke('setup:portal'),
  openCommunity: invoke('open:community'),
  openPatreon: invoke('open:patreon'),
  links: invoke('app:links'),
  setLanguage: invoke('app:setLanguage'),
  onSetupLine: callback => ipcRenderer.on('setup:line', (_event, line) => callback(line)),
  onLog: callback => ipcRenderer.on('logs:line', (_event, line) => callback(line)),
  onConnection: callback => ipcRenderer.on('connection', (_event, state) => callback(state)),
  onDeployLine: callback => ipcRenderer.on('deploy:line', (_event, line) => callback(line)),
  onDeployDone: callback => ipcRenderer.on('deploy:done', (_event, result) => callback(result)),
  onAlert: callback => ipcRenderer.on('alert', (_event, alert) => callback(alert))
});
